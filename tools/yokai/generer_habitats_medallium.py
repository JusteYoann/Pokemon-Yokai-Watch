#!/usr/bin/env python3
"""Generate the approved 151-species habitat pages; never split evolution families."""
import argparse
import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATEGORIES = [
    ('Prairies', 'GrasslandPkmn'), ('Forêts', 'ForestPkmn'),
    ('Rivières', 'WatersEdgePkmn'), ('Mer', 'SeaPkmn'),
    ('Grottes', 'CavePkmn'), ('Montagnes', 'MountainPkmn'),
    ('Terrains arides', 'RoughTerrainPkmn'), ('Villes', 'UrbanPkmn'),
    ('Rares', 'RarePkmn'),
]


def generate():
    rows = list(csv.DictReader((ROOT / 'data/yokai/habitats_valides.csv').open()))
    by = {r['species']: r for r in rows}
    assert len(rows) == len(by) == 151
    assert sorted(int(r['numero']) for r in rows) == list(range(1, 152))
    assert {r['habitat'] for r in rows} <= {n for n, _ in CATEGORIES}
    parent = {s: s for s in by}

    def find(s):
        while parent[s] != s:
            s = parent[s]
        return s

    edges = []
    # Each initializer is a single line; retain every branch, including items.
    for line in (ROOT / 'src/data/pokemon/evolution.h').read_text().splitlines():
        if not re.match(r'\s*\[SPECIES_\w+\]\s*=', line):
            continue
        species = re.findall(r'SPECIES_\w+', line)
        for target in species[1:]:
            assert species[0] in by and target in by
            edges.append((species[0], target))
            parent[find(target)] = find(species[0])
    assert len(edges) == 56, 'Evolution graph changed: review families before regenerating'
    families = defaultdict(list)
    for row in rows:
        families[find(row['species'])].append(row)
    grouped = defaultdict(list)
    family_report = []
    for family in families.values():
        habitats = {r['habitat'] for r in family}
        assert len(habitats) == 1, f'Family split: {family}'
        assert len(family) <= 4, 'Review pagination for new family larger than four'
        habitat = next(iter(habitats))
        grouped[habitat].append(family)
        family_report.append(dict(members=[int(r['numero']) for r in family],
                                  names=[r['nom'] for r in family], habitat=habitat))
    lines = ['// Generated by tools/yokai/generer_habitats_medallium.py.',
             '// Approved habitats, 151 Yo-kai, one page/habitat per evolution family.',
             '#define DEX_CATEGORY(name) {sDexCategory_##name, NELEMS(sDexCategory_##name)}', '']
    pages_report = []
    for cat, (name, ident) in enumerate(CATEGORIES):
        pages = []
        for family in grouped[name]:
            if not pages or len(pages[-1]) + len(family) > 4:
                pages.append([])
            pages[-1].extend(family)
        assert pages and len(pages) <= 255
        for p, page in enumerate(pages, 1):
            lines += [f'static const u16 sDexCategory_{ident}_Page{p}[] = {{']
            lines += [f"    {r['species']}," for r in page]
            lines += ['};', '']
            pages_report.append(dict(category=cat, habitat=name, page=p-1,
                                     species=[int(r['numero']) for r in page]))
        lines += [f'static const struct PokedexCategoryPage sDexCategory_{ident}[] = {{']
        lines += [f'    DEX_CATEGORY({ident}_Page{p}), ' for p in range(1, len(pages)+1)]
        lines += ['};', '']
    lines += ['struct {', '    const struct PokedexCategoryPage * page;',
              '    u8 count;', '} const gDexCategories[] = {']
    lines += [f'    DEX_CATEGORY({ident}),' for _, ident in CATEGORIES]
    lines += ['};', '']
    report = dict(passed=True, species_count=151, evolution_edges=len(edges),
                  family_count=len(families), families_with_evolutions=sum(len(f)>1 for f in families.values()),
                  counts=dict(Counter(r['habitat'] for r in rows)),
                  families=family_report, pages=pages_report,
                  scope='Approved source mapping and complete evolution graph; no runtime/visual claim.')
    return '\n'.join(lines), json.dumps(report, ensure_ascii=False, indent=2)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Require generated files to be up to date')
    args = parser.parse_args()
    header, report = generate()
    for path, data in [('src/data/pokemon/pokedex_categories.h', header),
                       ('QA_RECETTE_FINALE/POST_B13/medallium/CONTROLE_FAMILLES.json', report)]:
        p = ROOT / path
        if args.check:
            assert p.read_text() == data, f'Out of date: {p}'
        else:
            p.write_text(data)
    print('151 species, 56 evolution edges, complete families and <=4 sprites/page: PASS')

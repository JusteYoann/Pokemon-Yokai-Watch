#!/usr/bin/env python3
"""Graphe de marche conservateur: obstacles mobiles et barrières ouvrables libres.
Chaque arête est un pas; entrer dans un escalier applique son warp sans coût ajouté.
Les chutes et sorties du massif sont exclues. La distance ne surestime donc pas
un trajet débarrassé de ses obstacles temporaires.
"""
import json,re,struct,sys
sys.setrecursionlimit(20000)
from collections import deque
from pathlib import Path
R=Path(__file__).resolve().parents[2]
rows=json.loads((R/'docs/terre-heure-20261025/AUDIT_GROTTES.json').read_text())['maps']
layouts={v['id']:v for v in json.loads((R/'data/layouts/layouts.json').read_text())['layouts'] if 'id' in v}
walktypes={0,2,8,10,11,12,0x20,0x21,0x23,0x2a,0x2b,0x60,0x61,0x67,0x69,0x6c,0x6d,0x6e,0x6f}
def attributes(label,primary):
 name=re.sub(r'(?<!^)(?=[A-Z])','_',label.removeprefix('gTileset_')).lower()
 data=(R/'data/tilesets'/('primary' if primary else 'secondary')/name/'metatile_attributes.bin').read_bytes()
 return struct.unpack('<'+'I'*(len(data)//4),data)
graph=[];out=['// Generated by tools/yokai/generer_distances_terreur.py']
for row in rows:
 name=row['map'];d=json.loads((R/f'data/maps/{name}/map.json').read_text());l=layouts[d['layout']];w,h=l['width'],l['height']
 data=(R/l['blockdata_filepath']).read_bytes();tiles=struct.unpack('<'+'H'*(len(data)//2),data);a=attributes(l['primary_tileset'],True);b=attributes(l['secondary_tileset'],False)
 behaviors=[(a[t&1023] if t&1023<640 else b[(t&1023)-640])&511 for t in tiles]
 water=set(range(0x10,0x1c))|set(range(0x50,0x54));jumpdirs={0x38:(1,0),0x39:(-1,0),0x3a:(0,-1),0x3b:(0,1)}
 walk={i for i,t in enumerate(tiles) if ((t>>10)&3==0 and behaviors[i] in walktypes|water|{0x66}) or behaviors[i] in jumpdirs}
 jumps={i:jumpdirs[v] for i,v in enumerate(behaviors) if v in jumpdirs}
 script=(R/f'data/maps/{name}/scripts.inc').read_text()
 gates={int(y)*w+int(x) for x,y in re.findall(r'setmetatile\s+(\d+),\s*(\d+),\s*METATILE_Cave_Floor_\w+,\s*0',script)}
 walk|=gates;edges=[0]*(w*h)
 for i in walk:
  x,y=i%w,i//w
  for bit,(dx,dy) in enumerate(((0,1),(0,-1),(-1,0),(1,0))):
   nx,ny=x+dx,y+dy;j=ny*w+nx
   if 0<=nx<w and 0<=ny<h and j in walk and (i in gates or j in gates or i in jumps or j in jumps or behaviors[i] in water or behaviors[j] in water or tiles[i]>>12==tiles[j]>>12 or not tiles[i]>>12 or not tiles[j]>>12):edges[i]|=1<<bit
 packed=[edges[i]|((edges[i+1] if i+1<len(edges) else 0)<<4) for i in range(0,len(edges),2)]
 out.append('static const u8 sThWalk_'+name+'[] = {'+','.join(map(str,packed))+'};');graph.append({'map':name,'width':w,'height':h,'edges':edges,'ground':[int(v in (0,2,8,10,11,12,0x21,0x2b)) for v in behaviors],'jumps':[(cell%w,cell//w,cell%w+dx,cell//w+dy) for cell,(dx,dy) in jumps.items() if 0<=cell%w+dx<w and 0<=cell//w+dy<h and (cell//w+dy)*w+cell%w+dx in walk],'warps':d['warp_events'],'id':d['id'],'cave':next(i+1 for i,p in enumerate(('MtMoon','RockTunnel','SeafoamIslands','VictoryRoad','CeruleanCave','MtEmber')) if name.startswith(p))})
out.append('static const u8 *const sThWalkEdges[] = {'+','.join('sThWalk_'+g['map'] for g in graph)+'};')
links=[];safe_links=[];exits=[];ids={g['id']:i for i,g in enumerate(graph)}
for i,g in enumerate(graph):
 for warp in g['warps']:
  target=ids.get(warp['dest_map']);dest=None
  if target is not None:
   ws=graph[target]['warps'];idx=int(warp['dest_warp_id'])
   if idx<len(ws):dest=ws[idx]
  if target is None or graph[target]['cave']!=g['cave']:exits.append((i,warp['x'],warp['y']))
  link=(i,warp['x'],warp['y'],target if dest else 255,dest['x'] if dest else 0,dest['y'] if dest else 0);links.append(link)
  if dest and dest['dest_map']==g['id']:safe_links.append(link)
 for x,y,tx,ty in g['jumps']:links.append((i,x,y,i,tx,ty))
assert len(links)<255,len(links)
out.append('static const u8 sThCaveExits[][3] = {'+','.join('{'+','.join(map(str,v))+'}' for v in exits)+'};')
out.append('static const u8 sThStairs[][6] = {'+','.join('{'+','.join(map(str,v))+'}' for v in links)+'};')
out.append('static const u8 sThSafeTransitions[] = {'+','.join('1' if v in safe_links else '0' for v in links)+'};')
# A second graph keeps original barriers/boulder cells blocked. A selected door
# must have a route in this graph too, without solving another puzzle mid-event.
original=(R/'src/data/terre_heure_maps.h').read_text()
for g in graph:
 g['safe_labels']=list(map(int,re.search(r'sThLabels_'+re.escape(g['map'])+r'\[\] = \{([^}]+)',original)[1].split(',')))
transition={(a,x,y):(b,u,v) for a,x,y,b,u,v in links};safe_keys={(a,x,y) for a,x,y,b,u,v in safe_links};reverse=[{},{}]
for m,g in enumerate(graph):
 w=g['width']
 for cell,e in enumerate(g['edges']):
  x,y=cell%w,cell//w;source=(m,x,y)
  for bit,(dx,dy) in enumerate(((0,1),(0,-1),(-1,0),(1,0))):
   if not e>>bit&1:continue
   nxt=(m,x+dx,y+dy);target=transition.get(nxt,nxt)
   if target[0]==255:continue
   reverse[0].setdefault(target,[]).append(source)
   tm,tx,ty=target
   if (nxt not in transition or nxt in safe_keys) and g['safe_labels'][cell] and g['safe_labels'][(y+dy)*w+x+dx] and graph[tm]['safe_labels'][ty*graph[tm]['width']+tx]:reverse[1].setdefault(target,[]).append(source)
def reverse_bfs(node,which):
 d={node:0};q=deque([node])
 while q:
  a=q.popleft()
  for b in reverse[which].get(a,()):
   if b not in d:d[b]=d[a]+1;q.append(b)
 return d
# Review every viable ground tile, not only the former small demonstration pool.
# Articulation tiles are excluded so that the door never seals a passage.
for m,g in enumerate(graph):
 w=g['width'];labels=g['safe_labels'];visited={};low={};parent={};art=set();tick=[0]
 def adjacent(cell):
  x,y=cell%w,cell//w
  for bit,(dx,dy) in enumerate(((0,1),(0,-1),(-1,0),(1,0))):
   nx,ny=x+dx,y+dy;j=ny*w+nx
   if 0<=nx<w and 0<=ny<g['height'] and labels[j] and labels[j]==labels[cell] and g['edges'][cell]>>bit&1:yield j
 def visit(cell):
  tick[0]+=1;visited[cell]=low[cell]=tick[0];children=0
  for nxt in adjacent(cell):
   if nxt not in visited:
    parent[nxt]=cell;children+=1;visit(nxt);low[cell]=min(low[cell],low[nxt])
    if cell not in parent and children>1 or cell in parent and low[nxt]>=visited[cell]:art.add(cell)
   elif parent.get(cell)!=nxt:low[cell]=min(low[cell],visited[nxt])
 for cell,c in enumerate(labels):
  if c and cell not in visited:visit(cell)
 goals=[];packed=bytearray((len(labels)+7)//8)
 for cell,c in enumerate(labels):
  x,y=cell%w,cell//w
  if not c or not g['ground'][cell] or cell in art or len(list(adjacent(cell)))<3:continue
  if any(abs(x-v['x'])+abs(y-v['y'])<3 for v in g['warps']):continue
  goals.append((x,y));packed[cell//8]|=1<<(cell%8)
 g['door_candidates']=goals
 out.append('static const u8 sThDoorCells_'+g['map']+'[] = {'+','.join(map(str,packed))+'};')
out.append('static const u8 *const sThDoorCells[] = {'+','.join('sThDoorCells_'+g['map'] for g in graph)+'};')
eligible=[bytearray((len(g['edges'])+7)//8) for g in graph]
for m,g in enumerate(graph):
 queue=deque((m,x,y) for x,y in g['door_candidates']);distance={v:0 for v in queue}
 while queue:
  a=queue.popleft()
  for node in reverse[1].get(a,()):
   if node not in distance:distance[node]=distance[a]+1;queue.append(node)
 for (n,u,v),dist in distance.items():
  if n!=m:
   cell=v*graph[n]['width']+u;eligible[n][cell//8]|=1<<(cell%8)
for i,g in enumerate(graph):out.append('static const u8 sThEligible_'+g['map']+'[] = {'+','.join(map(str,eligible[i]))+'};')
out.append('static const u8 *const sThDoorEligibility[] = {'+','.join('sThEligible_'+g['map'] for g in graph)+'};')
print('Cellules éligibles par massif:',{p:sum(sum(v.bit_count() for v in eligible[i]) for i,g in enumerate(graph) if g['map'].startswith(p)) for p in ('MtMoon','RockTunnel','SeafoamIslands','VictoryRoad','CeruleanCave','MtEmber')})
(R/'src/data/terre_heure_distances.h').write_text('\n'.join(out)+'\n')
p=R/'docs/terre-heure-nathan-patrouilles-20261025';p.mkdir(parents=True,exist_ok=True)
(p/'GRAPHE_DISTANCES.json').write_text(json.dumps({'maps':graph,'stairs':links,'safe_stairs':safe_links},separators=(',',':'))+'\n')
print('Graphes générés',len(graph),'cartes',len(links),'escaliers')

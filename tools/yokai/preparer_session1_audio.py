#!/usr/bin/env python3
"""Apply music-only alias policy and inventory all maps/song references."""
import csv
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'QA_RECETTE_FINALE/SESSION_1_AUDIO'
OUT.mkdir(parents=True, exist_ok=True)
config = json.loads((ROOT/'data/yokai/audio_session1_aliases.json').read_text())
aliases = {r['source']: r['target'] for r in config['aliases']}
constants = {k:int(v) for k,v in re.findall(r'^#define\s+((?:MUS|SE)_\w+)\s+(\d+)\b',
            (ROOT/'include/constants/songs.h').read_text(), re.M)}
entries = re.findall(r'^\s*song\s+(\w+),\s*(\d+),\s*(\d+)',
                     (ROOT/'sound/song_table.inc').read_text(), re.M)
for source, target in aliases.items():
    assert source.startswith('MUS_') and target.startswith('MUS_YOKAI_')
    assert 256 <= constants[source] < constants['MUS_YOKAI_BICYCLE']
    assert entries[constants[source]][1:] == ('0', '0'), source
assert len(aliases) == len(config['aliases'])
text = '/* Generated by tools/yokai/preparer_session1_audio.py; BGM only. */\n'
text += 'static const u16 sYokaiMusicAliases[][2] = {\n'
text += ''.join(f'    {{{s}, {t}}},\n' for s,t in aliases.items())
text += '};\n'
(ROOT/'src/data/yokai_music_aliases.h').write_text(text)

changes = []
maps = {}
for path in sorted((ROOT/'data/maps').glob('*/map.json')):
    d = json.loads(path.read_text()); old = d['music']; name = path.parent.name
    new = aliases.get(old, old)
    # Safari deliberately uses a field theme rather than evolution music.
    if name.startswith('SafariZone_'): new = 'MUS_YOKAI_MYSTIC_GROVE'
    if name.startswith('PowerPlant'): new = 'MUS_YOKAI_HOPPERS_GORGE'
    if name=='FiveIsland_RocketWarehouse': new = 'MUS_YOKAI_DODGY'
    if name=='ThreeIsland_BerryForest' or name.startswith('SevenIsland_TanobyRuins_') or name=='SevenIsland_SevaultCanyon_TanobyKey':
        new='MUS_YOKAI_MYSTIC_GROVE'
    if new != old:
        d['music'] = new
        path.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
        changes.append(dict(map=name,before=old,after=new))
    maps[name] = (path,d)
# Explicit roadside Sevii interiors: match the road rather than the island town.
for name,parent in [('OneIsland_KindleRoad_EmberSpa','OneIsland_KindleRoad'),
                    ('SevenIsland_SevaultCanyon_House','SevenIsland_SevaultCanyon'),
                    ('FiveIsland_ResortGorgeous_House','FiveIsland_ResortGorgeous')]:
    path,d=maps[name];old=d['music'];new=maps[parent][1]['music']
    if new!=old:
        d['music']=new;path.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
        changes.append(dict(map=name,before=old,after=new))
# Ordinary route buildings must match their actual route, including both floors
# of roadside care centres; no change to custom scenario/gym themes.
for name,(path,d) in maps.items():
    parent = name.split('_')[0]
    if parent.startswith('Route') and parent in maps and name != parent:
        old = d['music']; new = maps[parent][1]['music']
        if old != new:
            d['music'] = new
            path.write_text(json.dumps(d,ensure_ascii=False,indent=2)+'\n')
            changes.append(dict(map=name,before=old,after=new))

def csvfile(name, rows, fields):
    with (OUT/name).open('w',newline='') as f:
        w=csv.DictWriter(f,fields,lineterminator='\n');w.writeheader();w.writerows(rows)

maprows=[]
active = set(json.loads((ROOT/'data/yokai/audio_loops.json').read_text())['active_tracks'])
titles={t['number']:t['title'] for t in json.loads((ROOT/'data/yokai/audio_candidates.json').read_text())['tracks']}
for name,(_,d) in maps.items():
    m=d['music']; n=constants.get(m,65535)-346
    status='OST_PRIVEE_ACTIVE' if n in active else 'OST_EN_ATTENTE_REPLI_NATIF' if m.startswith('MUS_YOKAI') else 'SILENCE_INTENTIONNEL' if m=='MUS_NONE' else 'NATIF_CONSERVE'
    maprows.append(dict(map=name,music=m,private_slot=n if m.startswith('MUS_YOKAI') else '',theme=titles.get(n,''),status=status))
csvfile('AFFECTATIONS_425_CARTES.csv',maprows,['map','music','private_slot','theme','status'])
references=[]
for folder in ['src','data']:
    for p in sorted((ROOT/folder).rglob('*')):
        if p.suffix not in ['.c','.h','.inc','.json']:continue
        if p.name=='yokai_music_aliases.h':continue
        for line_no,line in enumerate(p.read_text(errors='replace').splitlines(),1):
            for source in sorted(set(re.findall(r'\bMUS_\w+\b',line))):
                references.append(dict(file=str(p.relative_to(ROOT)),line=line_no,source=source,
                                       resolved=aliases.get(source,source),
                                       scope='Source reference; reachability not inferred'))
csvfile('REFERENCES_MUSICALES_SOURCES.csv',references,['file','line','source','resolved','scope'])
songrows=[]
names={v:k for k,v in constants.items() if k.startswith('MUS_')}
for n in range(256,len(entries)):
    name=names.get(n,str(n)); target=aliases.get(name,name)
    status='ALIAS_OST' if name in aliases else 'OST_EXPLICITE' if n>=347 else 'FANFARE_NATIVE_CONSERVEE' if entries[n][1]!='0' else 'NATIF_CONSERVE'
    slot=constants.get(target,0)-346 if target.startswith('MUS_YOKAI') else 0
    songrows.append(dict(id=n,name=name,sequence=entries[n][0],player=entries[n][1],resolved=target,
                         theme=titles.get(slot,''),private_sample_active=slot in active,status=status))
csvfile('AFFECTATIONS_MOTEUR_ET_JINGLES.csv',songrows,['id','name','sequence','player','resolved','theme','private_sample_active','status'])
previous=OUT/'MODIFICATIONS_CARTES.json'
if changes:
    oldchanges=json.loads(previous.read_text())['changes'] if previous.exists() else []
    previous.write_text(json.dumps(dict(changes=oldchanges+changes),ensure_ascii=False,indent=2)+'\n')
(OUT/'AUDIT_SOURCES.json').write_text(json.dumps(dict(maps=len(maprows),
    statuses=dict(Counter(r['status'] for r in maprows)), bgm_aliases=len(aliases),
    all_se_ids_unchanged=True, scope='Source audit, not proof of all runtime events.'),ensure_ascii=False,indent=2)+'\n')
print('Maps',len(maprows),'music-only aliases',len(aliases),'map changes',len(changes))

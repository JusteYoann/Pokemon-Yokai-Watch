#!/usr/bin/env python3
"""Rebuild numeric ROM catalogue exclusively from the game's active data.

No changes to species, learnsets or TM compatibility. HMs and tutors are excluded.
--check performs a read-only reproducibility check.
"""
import argparse, hashlib, json, re
from pathlib import Path
R=Path(__file__).resolve().parents[2]
inputs=['data/yokai/noms_affiches.json','include/constants/moves.h','include/constants/pokemon.h','include/constants/abilities.h','src/data/pokemon/species_info.h','src/data/pokemon/level_up_learnset_pointers.h','src/data/pokemon/level_up_learnsets.h','src/data/pokemon/tmhm_learnsets.h','src/data/party_menu.h','src/data/battle_moves.h','src/battle_main.c']
inputs.append('include/battle_main.h')
sources={p:(R/p).read_text() for p in inputs}
constants={}
for p in inputs[1:4]+[inputs[-1]]:
 for k,v in re.findall(r'^#define\s+(\w+)\s+(0x[\da-fA-F]+|\d+)\s*(?:$|//)',sources[p],re.M):constants[k]=int(v,0)
def number(s):return int(s) if s.isdigit() else constants[s]
rows=json.loads(sources[inputs[0]]);assert len(rows)==151
pointers=dict(re.findall(r'\[(SPECIES_\w+)\]\s*=\s*(\w+)',sources[inputs[5]]))
learnsets={k:[(int(l),constants[m]) for l,m in re.findall(r'LEVEL_UP_MOVE\((\d+), (MOVE_\w+)\)',v)] for k,v in re.findall(r'(\w+)\[\]\s*=\s*\{(.*?)\};',sources[inputs[6]],re.S)}
tms=re.search(r'sTMHMMoves\[\]\s*=\s*\{(.*?)\};',sources[inputs[8]],re.S)[1]
tms=re.findall(r'MOVE_\w+',tms);assert len(tms)==58
out=['/* Generated by generer_spiraton_catalogue.py; do not edit. */',
'struct SpiratonSpecies { u16 start, count; u8 stats[6], types[2], ability; };',
'struct SpiratonLegalMove { u16 move; u8 level; };',
'struct SpiratonMove { u8 power, type, accuracy, pp; s8 priority; };']
species=['    {0},'];legal=[];counts={};base_stats=[[0]*6];species_pools=[{}];move_info={}
for x in rows:
 sp=x['species_constant'];num=int(x['species_id']);assert num==len(species)
 body=re.search(r'\['+sp+r'\]\s*=\s*\{(.*?)\n    \}',sources[inputs[4]],re.S)[1]
 stats=[int(re.search(r'\.'+k+r'\s*=\s*(\d+)',body)[1]) for k in ['baseHP','baseAttack','baseDefense','baseSpeed','baseSpAttack','baseSpDefense']]
 base_stats.append(stats)
 types=[constants[t] for t in re.search(r'\.types\s*=\s*\{([^}]+)',body)[1].replace(' ','').split(',')]
 ability=constants[re.search(r'\.abilities\s*=\s*\{\s*(\w+)',body)[1]]
 pool={}
 for level,move in learnsets[pointers[sp]]:pool[move]=min(level,pool.get(move,100))
 line=re.search(r'\['+sp+r'\]\s*=\s*([^\n]+)',sources[inputs[7]])[1]
 for tm in re.findall(r'TMHM\(TM(\d+)_\w+\)',line):pool[constants[tms[int(tm)-1]]]=0
 species_pools.append(pool)
 assert len(pool)>=4
 start=len(legal)
 legal.extend('    {%d, %d},'%(m,l) for m,l in sorted(pool.items()))
 species.append('    {%d, %d, {%s}, {%s}, %d},'%(start,len(pool),', '.join(map(str,stats)),', '.join(map(str,types)),ability))
 counts[x['numero_yokai']]=len(pool)
out+=['static const struct SpiratonSpecies sSpiratonSpecies[152] = {',*species,'};','static const struct SpiratonLegalMove sSpiratonLegalMoves[] = {',*legal,'};','static const struct SpiratonMove sSpiratonMoves[] = {']
for name,body in re.findall(r'\[(MOVE_\w+)\]\s*=\s*\{(.*?)\n    \}',sources[inputs[9]],re.S):
 values=[number(re.search(r'\.'+key+r'\s*=\s*([^,\n]+)',body)[1].strip()) if key!='priority' else int(re.search(r'\.priority\s*=\s*(-?\d+)',body)[1]) for key in ['power','type','accuracy','pp','priority']]
 assert constants[name]==len([l for l in out if l.startswith('    /* MOVE_')])
 move_info[constants[name]]=values
 out.append('    /* %s */ {%s},'%(name,', '.join(map(str,values))))
out+=['};','static const u8 sSpiratonTypeChart[18][18] = {']
chart=[[10]*18 for _ in range(18)]
typebody=re.search(r'gTypeEffectiveness\[336\]\s*=\s*\{(.*?)\};',sources[inputs[10]],re.S)[1]
for atk,defn,mul in re.findall(r'(TYPE_\w+),\s*(TYPE_\w+),\s*(TYPE_MUL_\w+)',typebody):
 if constants[atk]<18 and constants[defn]<18:chart[constants[atk]][constants[defn]]=constants[mul]
out+=['    {'+', '.join(map(str,r))+'},' for r in chart]+['};','static const u16 sSpiratonPhaseStats[8][152][8] = {']
for level in range(56,64):
 out.append('    {')
 for i,stats in enumerate(base_stats):
  values=[((2*b+24)*level)//100+5 for b in stats] if i else [0]*6
  if i:values[0]+=level+5
  values += [((2*level//5+2)*values[k]*256)//50 for k in (1,4)]
  out.append('        {'+', '.join(map(str,values))+'},')
 out.append('    },')
out+=['};','static const u16 sSpiratonBulkRecip[241] = {', ', '.join(str(65536//(20+p)) for p in range(241)), '};','']
# Exact Pareto pruning for the counter-selection score only. Full move selection
# still scans every legal move for the chosen species. Within one type/priority
# class, greater power AND accuracy cannot score less for any public opponent.
threat_moves=[];ranges=[]
for level in range(56,64):
 row=[(0,0)]
 for pool in species_pools[1:]:
  eligible=[m for m,l in sorted(pool.items()) if l<=level and move_info[m][0]>1]
  kept=[]
  for m in eligible:
   p,t,a,pp,pr=move_info[m];a=a or 100
   dominated=False
   for other in eligible:
    if other==m:continue
    op,ot,oa,opp,opr=move_info[other];oa=oa or 100
    if ot==t and (pr>0)==(opr>0) and op>=p and oa>=a and (op>p or oa>a or other<m):
     dominated=True;break
   if not dominated:kept.append(m)
  row.append((len(threat_moves),len(kept)));threat_moves.extend(kept)
 ranges.append(row)
out+=['static const u16 sSpiratonThreatMoves[] = {', ', '.join(map(str,threat_moves)), '};',
      'struct SpiratonThreatRange { u16 start, count; };',
      'static const struct SpiratonThreatRange sSpiratonThreatRanges[8][152] = {']
for row in ranges:out+=['    {'+', '.join('{%d,%d}'%r for r in row)+'},']
out+=['};','']
artifacts={'src/data/spiraton_catalogue.h':'\n'.join(out),'data/yokai/spiraton/catalogue_provenance.json':json.dumps({'source_sha256':{p:hashlib.sha256(sources[p].encode()).hexdigest() for p in inputs},'species':151,'legal_move_entries':len(legal),'hm_and_tutor_moves_added':False,'pool_counts':counts},indent=2)+'\n'}
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
for p,value in artifacts.items():
 if args.check:assert (R/p).read_text()==value,p
 else:(R/p).write_text(value)
print('Catalogue verified' if args.check else 'Catalogue generated',len(legal),'legal entries')

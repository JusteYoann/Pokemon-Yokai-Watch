#!/usr/bin/env python3
"""Read native candidate PNG, pack indexed 4bpp tiles for four hardware objects.
Does not draw, resize or recolor the source image. Palette is rounded to RGB555.
"""
from pathlib import Path
from PIL import Image
import hashlib,json
R=Path(__file__).resolve().parents[2];p=R/'docs/don-spiraton/phase-a/sprite-harmonise-128x96-candidat.png'
im=Image.open(p).convert('RGBA');assert im.size==(128,96)
colors=sorted({c[:3] for c in im.getdata() if c[3]});assert len(colors)<=15
assert {c[3] for c in im.getdata()}=={0,255}
pal=[0]+[(r>>3)|((g>>3)<<5)|((b>>3)<<10) for r,g,b in colors];pal += [0]*(16-len(pal));assert len(set(pal[1:]))==15
indices={c:i+1 for i,c in enumerate(colors)};tiles=[]
# Two64x64 objects then two64x32 objects, sequential tiles inside each.
for x,y,w,h in [(0,0,64,64),(64,0,64,64),(0,64,64,32),(64,64,64,32)]:
 for ty in range(y,y+h,8):
  for tx in range(x,x+w,8):
   for iy in range(8):
    for ix in range(0,8,2):
     a,b=im.getpixel((tx+ix,ty+iy)),im.getpixel((tx+ix+1,ty+iy))
     tiles.append((indices[a[:3]] if a[3] else 0)|((indices[b[:3]] if b[3] else 0)<<4))
assert len(tiles)==6144
out=['/* Generated by convertir_spiraton_apercu.py; candidate only, not production. */','static const u16 sSpiratonPreviewPalette[16] = {'+', '.join(hex(c) for c in pal)+'};','static const u8 sSpiratonPreviewTiles[6144] = {']
for i in range(0,len(tiles),32):out.append('    '+','.join(hex(c) for c in tiles[i:i+32])+',')
out.append('};\n');(R/'src/data/spiraton_art_preview.h').write_text('\n'.join(out))
(R/'docs/don-spiraton/phase-a/CONVERSION.json').write_text(json.dumps(dict(candidate_only=True,native_canvas=list(im.size),visible_bbox=im.getbbox(),opaque_colors=len(colors),transparency='binary, palette index0',palette_format='GBA RGB555',obj_tiles=192,obj_vram_bytes=6144,hardware_objects=4,source_sha256=hashlib.sha256(p.read_bytes()).hexdigest()),indent=2)+'\n')
print('Packed candidate:',len(tiles),'bytes,',len(colors),'opaque colors, bbox',im.getbbox())
